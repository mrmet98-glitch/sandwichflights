-- Sandwich Flight Planner v1.2 — Cloudflare D1 schema + seed data
-- Safe to run on a fresh D1 database. Built-in searches/permutations use INSERT OR IGNORE.

CREATE TABLE IF NOT EXISTS searches (
  id TEXT PRIMARY KEY,
  ticket_type TEXT NOT NULL,
  leg1_date TEXT NOT NULL,
  leg1_origin TEXT NOT NULL,
  leg1_destination TEXT NOT NULL,
  leg2_date TEXT,
  leg2_origin TEXT,
  leg2_destination TEXT,
  what_to_search TEXT NOT NULL,
  sort_order INTEGER NOT NULL,
  is_custom INTEGER NOT NULL DEFAULT 0 CHECK (is_custom IN (0,1))
);

CREATE TABLE IF NOT EXISTS fare_options (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  search_id TEXT NOT NULL REFERENCES searches(id) ON DELETE CASCADE,
  option_number INTEGER NOT NULL,
  pricing_type TEXT NOT NULL DEFAULT 'cash' CHECK (pricing_type IN ('cash','points')),
  total_price REAL,
  currency TEXT NOT NULL DEFAULT 'USD',
  points_amount INTEGER,
  points_program TEXT,
  taxes_fees REAL,
  taxes_currency TEXT NOT NULL DEFAULT 'USD',
  point_value_cents REAL,
  comparison_value_usd REAL,
  booking_source TEXT,
  notes TEXT,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(search_id, option_number)
);

CREATE TABLE IF NOT EXISTS flight_segments (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  option_id INTEGER NOT NULL REFERENCES fare_options(id) ON DELETE CASCADE,
  direction TEXT NOT NULL CHECK (direction IN ('outbound','return')),
  segment_order INTEGER NOT NULL,
  entered_date TEXT NOT NULL,
  entered_flight_number TEXT NOT NULL,
  ident TEXT,
  ident_iata TEXT,
  ident_icao TEXT,
  actual_ident TEXT,
  origin_code TEXT,
  origin_iata TEXT,
  origin_icao TEXT,
  origin_name TEXT,
  origin_city TEXT,
  origin_timezone TEXT,
  destination_code TEXT,
  destination_iata TEXT,
  destination_icao TEXT,
  destination_name TEXT,
  destination_city TEXT,
  destination_timezone TEXT,
  scheduled_out_utc TEXT,
  scheduled_in_utc TEXT,
  aircraft_type TEXT,
  cabin TEXT,
  source_mode TEXT,
  fetched_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lookup_json TEXT,
  UNIQUE(option_id, direction, segment_order)
);

CREATE INDEX IF NOT EXISTS idx_segments_option ON flight_segments(option_id);
CREATE INDEX IF NOT EXISTS idx_options_search ON fare_options(search_id);

CREATE TABLE IF NOT EXISTS airport_cache (
  airport_code TEXT PRIMARY KEY,
  code_iata TEXT,
  code_icao TEXT,
  name TEXT,
  city TEXT,
  timezone TEXT,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS permutations (
  variant INTEGER PRIMARY KEY,
  oct_date TEXT NOT NULL,
  standalone_one_way TEXT NOT NULL REFERENCES searches(id),
  round_trip_1 TEXT NOT NULL REFERENCES searches(id),
  round_trip_2 TEXT NOT NULL REFERENCES searches(id),
  round_trip_3 TEXT NOT NULL REFERENCES searches(id),
  structure TEXT NOT NULL
);

